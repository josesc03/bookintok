"""Generates the Android vector drawables of the logo from the same paths as logo-symbol.svg.

Run from the repository root: python branding/generate_android_icons.py
"""
from pathlib import Path

RES = Path(__file__).resolve().parent.parent / "frontend/app/src/main/res"

INK = "#FF45202F"
GREEN = "#FF52D974"
WHITE = "#FFFFFFFF"
STROKE = "4.2"

LEFT_PAGE = "M50,50 C43,44 32,41 20,42 Q16,42.3 16,46 L16,78 Q16,81.5 20,81.2 C32,80.5 43,83 50,89 Z"
RIGHT_PAGE = "M50,50 C57,44 68,41 80,42 Q84,42.3 84,46 L84,78 Q84,81.5 80,81.2 C68,80.5 57,83 50,89 Z"
SPINE = "M50,50 L50,89"
PIN = "M50,55 C45.5,47 36,39 36,26 A14,14 0 1,1 64,26 C64,39 54.5,47 50,55 Z"
HOLE = "M45,26 A5,5 0 1,0 55,26 A5,5 0 1,0 45,26 Z"


def paths(mono: bool) -> str:
    page_fill = "#00000000" if mono else WHITE
    ink = "#FF000000" if mono else INK
    pin_fill = ink if mono else GREEN
    hole = "" if mono else f'<path android:pathData="{HOLE}" android:fillColor="{WHITE}" android:strokeColor="{ink}" android:strokeWidth="3.6"/>'
    # Monochrome icons are a single colour: the pin is solid with its hole cut out (even-odd)
    pin = (
        f'<path android:pathData="{PIN} {HOLE}" android:fillType="evenOdd" android:fillColor="{pin_fill}" '
        f'android:strokeColor="{ink}" android:strokeWidth="{STROKE}" android:strokeLineJoin="round"/>'
        if mono
        else f'<path android:pathData="{PIN}" android:fillColor="{pin_fill}" android:strokeColor="{ink}" '
        f'android:strokeWidth="{STROKE}" android:strokeLineJoin="round"/>'
    )
    book = "".join(
        f'<path android:pathData="{d}" android:fillColor="{fill}" android:strokeColor="{ink}" '
        f'android:strokeWidth="{STROKE}" android:strokeLineCap="round" android:strokeLineJoin="round"/>'
        for d, fill in ((LEFT_PAGE, page_fill), (RIGHT_PAGE, page_fill), (SPINE, "#00000000"))
    )
    return book + pin + hole


def vector(size_dp: int, viewport: int, body: str, transform: str = "") -> str:
    group_open = f"<group {transform}>" if transform else ""
    group_close = "</group>" if transform else ""
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by branding/generate_android_icons.py: edit that script, not this file. -->\n"
        f'<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="{size_dp}dp" '
        f'android:height="{size_dp}dp" android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">'
        f"{group_open}{body}{group_close}</vector>\n"
    )


# Launcher layers are 108dp; only the centre 66dp is always visible, so the symbol is scaled into it
LAUNCHER = 'android:translateX="26" android:translateY="25.7" android:scaleX="0.56" android:scaleY="0.56"'

files = {
    "drawable/ic_logo.xml": vector(96, 100, paths(mono=False)),
    "drawable/ic_launcher_foreground.xml": vector(108, 108, paths(mono=False), LAUNCHER),
    "drawable/ic_launcher_monochrome.xml": vector(108, 108, paths(mono=True), LAUNCHER),
    "mipmap-anydpi-v26/ic_launcher.xml": (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
        "</adaptive-icon>\n"
    ),
    "values/ic_launcher_background.xml": (
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
        '    <color name="ic_launcher_background">#D6EFDA</color>\n</resources>\n'
    ),
}

for name, content in files.items():
    path = RES / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print("wrote", path.relative_to(RES))
