import kotlinx.coroutines.test.setMain
import kotlinx.serialization.json.Json
import org.junit.rules.TestWatcher
import org.junit.runner.Description

val testJson = Json { ignoreUnknownKeys = true }

/** An HttpClient whose server is [handler]; every request is recorded in [requests]. */
class FakeServer(private val handler: MockRequestHandleScope.(HttpRequestData) -> HttpResponseData) {
    val requests = mutableListOf<HttpRequestData>()

    val client = HttpClient(MockEngine { request ->
        requests += request
        handler(request)
    }) {
        install(ContentNegotiation) { json(testJson) }
    }
}

fun MockRequestHandleScope.json(body: String, status: HttpStatusCode = HttpStatusCode.OK) =
    respond(body, status, headersOf(HttpHeaders.ContentType, "application/json"))

/** Replaces Dispatchers.Main, which does not exist in JVM unit tests. */
@OptIn(ExperimentalCoroutinesApi::class)
class MainDispatcherRule(val dispatcher: TestDispatcher = UnconfinedTestDispatcher()) : TestWatcher() {
    override fun starting(description: Description) = Dispatchers.setMain(dispatcher)

    override fun finished(description: Description) = Dispatchers.resetMain()
}
