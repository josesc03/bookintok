package com.bookintok.api.image

import org.springframework.beans.factory.annotation.Value
import org.springframework.stereotype.Component
import java.nio.file.Files
import java.nio.file.Path

/** Where book photos are kept. Swapping in S3 or similar only needs another implementation. */
interface ImageStorage {
    fun save(key: String, bytes: ByteArray)

    fun load(key: String): ByteArray?

    fun delete(key: String)
}

/** Stores photos as files in a directory (a Docker volume in production). */
@Component
class FileSystemImageStorage(@Value("\${bookintok.images.dir}") directory: String) : ImageStorage {

    private val root: Path = Path.of(directory).toAbsolutePath().normalize().also { Files.createDirectories(it) }

    override fun save(key: String, bytes: ByteArray) {
        Files.write(resolve(key), bytes)
    }

    override fun load(key: String): ByteArray? = resolve(key).takeIf { Files.exists(it) }?.let { Files.readAllBytes(it) }

    override fun delete(key: String) {
        Files.deleteIfExists(resolve(key))
    }

    /** Keys are generated by the server, but they are still checked so a key can never escape the directory. */
    private fun resolve(key: String): Path {
        require(KEY.matches(key)) { "Invalid image key" }
        return root.resolve("$key.jpg")
    }

    private companion object {
        val KEY = Regex("^[a-zA-Z0-9-]{1,100}$")
    }
}
